def panels(items, label, h=186):
    """三栏示意图（与教师 figTolerance 同一版式）。items=[(标签, 颜色, 内容svg函数(x0), 说明)]"""
    n = len(items); w = 192 if n == 3 else 294; gap = 14 if n == 3 else 16
    s = '<svg viewBox="0 0 620 %d" xmlns="http://www.w3.org/2000/svg" role="img" aria-label="%s">' % (h, esc(label))
    for i, (tag, col, inner, note) in enumerate(items):
        x = 8 + i * (w + gap)
        s += '<rect x="%d" y="10" width="%d" height="%d" rx="9" fill="#fdfcf9" stroke="%s"/>' % (x, w, h - 36, LINE)
        s += '<text x="%d" y="26" font-size="9.5" font-family="monospace" fill="%s" letter-spacing=".8">%s</text>' % (x + 12, col, esc(tag))
        s += inner(x, w)
        s += '<text x="%d" y="%d" font-size="9.5" fill="#454545">%s</text>' % (x + 12, h - 12, esc(note))
    return s + '</svg>'
